            <section class="overview">
                <h2>Aperçu de la série</h2>
                <p>"Suits: Avocats sur Mesure" est une série télévisée américaine créée par Aaron Korsh et diffusée pour la première fois le 23 juin 2011 sur USA Network. La série suit les avocats d'un prestigieux cabinet juridique de New York, Pearson Hardman. La série se distingue par ses intrigues captivantes, ses dialogues vifs et ses personnages charismatiques.</p>
            </section>
            <section class="synopsis">
                <h2>Synopsis</h2>
                <p>La série met en scène Harvey Specter, un brillant avocat associé, et Mike Ross, un jeune homme brillant avec une mémoire photographique, qui n'a jamais terminé ses études de droit. Harvey recrute Mike comme associé, malgré son absence de diplôme en droit. Ensemble, ils naviguent à travers des affaires complexes tout en gardant le secret de la véritable identité de Mike.</p>
                <p>Suits explore les thèmes de l'ambition, de la loyauté et de la lutte pour le pouvoir dans le monde du droit. Les personnages doivent jongler entre leurs défis professionnels et personnels tout en maintenant l'apparence d'un cabinet juridique prospère.</p>
